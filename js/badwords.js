// 금지어가 들어 있지만 괜찮은 말 (먼저 지우고 검사해요)
export const ALLOW_WORDS = ['시발점', '시발역', '새끼손가락', '새끼발가락', '새끼줄', '새끼고양이', '자위대', '애비뉴', '느그적'];

const norm = (s) => String(s || '').toLowerCase().normalize('NFC').replace(/[^0-9a-z가-힣ㄱ-ㅎㅏ-ㅣ]/g, '');

// 걸린 금지어를 돌려줘요 (없으면 '')
export function findBad(text) {
  let t = norm(text);
  if (!t) return '';
  for (const a of ALLOW_WORDS) t = t.split(norm(a)).join('');
  const noDigit = t.replace(/[0-9]/g, '');
  for (const w of BAD_WORDS) { const n = norm(w); if (t.includes(n) || noDigit.includes(n)) return w; }
  return '';
}
